"""Draws the Weft mark (a ball of yarn: a ring and two arcs, weft-icon.zip, 2026-11-08) into every file
that shows it, from one geometry, each centred exactly on its canvas (the mark's box is the ring).

  launcher  app/src/main/res/drawable/ic_launcher_foreground.xml   40 dp of the 108 dp canvas (like Burrow's)
            app/src/main/res/drawable/ic_launcher_monochrome.xml   the same, for themed icons
  in app    app/src/main/res/drawable/ic_weft.xml                   20 of 24 units, black (tinted where used)
            app/src/main/res/drawable/ic_notification.xml           the same, white
  store     release/icon.svg (512, full square: Play masks it)     284 px, the launcher's share of what shows
  site      site/weft.svg (rounded tile)

usage: python3 tools/weft_mark.py      then render release/icon.svg to release/icon-512.png (headless Chrome)
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GREEN = "#2A6F52"   # the logo's tile
STROKE = 5.5        # in the mark's 100-unit space
SIZE = 44 + STROKE  # the ring's outer width: the whole mark
PATHS = [
    "M28,50 a22,22 0 1,0 44,0 a22,22 0 1,0 -44,0",
    "M28.3,46.3 A30,30 0 0,1 53.7,71.7",
    "M35.4,33.5 A44,44 0 0,1 66.5,64.6",
]


def group(canvas, mark):
    """Scale and offset that put the mark, `mark` wide, in the middle of a `canvas` square."""
    s = mark / SIZE
    t = canvas / 2 - 50 * s
    return s, t


def vector(canvas_dp, viewport, mark, color, comment):
    s, t = group(viewport, mark)
    paths = "\n".join(
        f'        <path android:strokeColor="{color}" android:strokeWidth="{STROKE}" android:strokeLineCap="round" '
        f'android:pathData="{d}" />' for d in PATHS)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by tools/weft_mark.py: edit the geometry there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{canvas_dp}dp" android:height="{canvas_dp}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
    <group android:scaleX="{s:.5f}" android:scaleY="{s:.5f}" android:translateX="{t:.4f}" android:translateY="{t:.4f}">
{paths}
    </group>
</vector>
'''


def svg(size, mark, tile_radius, bg, fg):
    s, t = group(size, mark)
    rect = f'<rect width="{size}" height="{size}"{f" rx={chr(34)}{tile_radius}{chr(34)}" if tile_radius else ""} fill="{bg}"/>'
    paths = "".join(f'<path d="{d}"/>' for d in PATHS)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">\n'
            f'  <!-- The Weft mark (weft-icon.zip, 2026-11-08), centred. Generated by tools/weft_mark.py. -->\n'
            f'  {rect}\n'
            f'  <g transform="translate({t:.3f} {t:.3f}) scale({s:.5f})" fill="none" stroke="{fg}" stroke-width="{STROKE}" stroke-linecap="round">{paths}</g>\n'
            f'</svg>\n')


def write(rel, text):
    with open(os.path.join(ROOT, rel), "w") as f:
        f.write(text)
    print(rel)


D = "app/src/main/res/drawable/"
write(D + "ic_launcher_foreground.xml", vector(108, 108, 40, "#FFFFFFFF", "Launcher mark: white on the logo green (ic_launcher_background), 40 dp of the 108 dp canvas, centred."))
write(D + "ic_launcher_monochrome.xml", vector(108, 108, 40, "#FF000000", "Themed-icon mark (Android 13+): the launcher mark in one colour."))
write(D + "ic_weft.xml", vector(24, 24, 20, "#FF000000", "The Weft mark for in-app use (Welcome, About, More, sheets, widget loading): tinted by the theme."))
write(D + "ic_notification.xml", vector(24, 24, 20, "#FFFFFFFF", "Notification small icon: the Weft mark as one white shape."))
write("release/icon.svg", svg(512, 284, 0, GREEN, "#FFFFFF"))
write("site/weft.svg", svg(512, 284, 114, GREEN, "#FFFFFF"))
